import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {RoadsterSim} from '../dist/physics.js';
import {replayEligibility,prepareRecordedStateForCurrentModel,executeExperiment} from '../dist/experiment-records.js';
const bytes=readFileSync('qa/browser-3.24/final/browser-replay.json'),record=JSON.parse(bytes),original=JSON.stringify(record);
assert.equal(record.identity.modelVersion,'3.24.0');
assert.equal(replayEligibility(record).exact,false);assert.equal(replayEligibility(record).recompute,true);
const createSim=s=>new RoadsterSim(s.params,{world:s.worldType}),sim=createSim(record.initialSnapshot.physical);
assert.throws(()=>prepareRecordedStateForCurrentModel(record,sim),/迁移器/);
const mapped=prepareRecordedStateForCurrentModel(record,sim,{recompute:true});
assert.deepEqual(mapped.compatibility.migration.changed,['modelVersion']);
assert.deepEqual(mapped.compatibility.migration.addedDefaultState,[]);
assert.deepEqual({...mapped.physical,modelVersion:'3.24.0'},record.initialSnapshot.physical);
sim.importState(mapped.physical);
const result=await executeExperiment(record,{createSim,recompute:true,yieldEvery:0});
assert.equal(result.status,'completed');assert.equal(result.completedSteps,record.stepCount);
assert.equal(result.execution,'current-model-recompute');assert.equal(JSON.stringify(record),original);
const other=structuredClone(record);other.initialSnapshot.physical.geometryIdentity.signature='00000000';
assert.throws(()=>prepareRecordedStateForCurrentModel(other,sim,{recompute:true}),/几何/);
mkdirSync('qa/release-1.0',{recursive:true});writeFileSync('qa/release-1.0/record-migration.json',JSON.stringify({status:'passed',source:'qa/browser-3.24/final/browser-replay.json',sourceSha256:createHash('sha256').update(bytes).digest('hex'),steps:result.completedSteps,compatibility:result.compatibility,reproduction:result.reproduction,sourceUnchanged:true},null,2)+'\n');
console.log('PASS explicit 3.24 → 1.0 recomputation of actual browser record; full initial state and source preserved');
